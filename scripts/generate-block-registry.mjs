import { readFile, stat, writeFile } from "node:fs/promises"
import path from "node:path"

const root = process.cwd()
const registryPath = path.join(root, "registry.json")
const previewMapPath = path.join(
  root,
  "app",
  "(view)",
  "view",
  "[slug]",
  "preview-map.ts",
)
const categoryPreviewMapPath = path.join(
  root,
  "components",
  "block-category-preview-map.ts",
)
const categoryPreviewComponentsPath = path.join(
  root,
  "components",
  "block-category-previews.tsx",
)

function compareByTitle(a, b) {
  return a.title.localeCompare(b.title, "en", { sensitivity: "base" })
}

function toTitle(value) {
  return value
    .split("-")
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ")
}

function toPascalCase(value) {
  return value
    .split("-")
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("")
}

async function fileExists(filePath) {
  try {
    const stats = await stat(filePath)
    return stats.isFile()
  } catch {
    return false
  }
}

async function readJson(filePath) {
  const raw = await readFile(filePath, "utf8")
  return JSON.parse(raw)
}

function getBlockItems(registry) {
  if (!Array.isArray(registry.items)) {
    throw new Error("Root registry.json must include an items array.")
  }

  return registry.items
    .filter((item) => item.type === "registry:block")
    .map((item) => {
      if (!item.name || !Array.isArray(item.categories) || item.categories.length === 0) {
        throw new Error(`Block registry item "${item.name ?? "(unknown)"}" must include a category.`)
      }

      if (!Array.isArray(item.files) || item.files.length === 0) {
        throw new Error(`Block registry item "${item.name}" must include files.`)
      }

      return {
        name: item.name,
        title: item.title ?? toTitle(item.name),
        category: item.categories[0],
        files: item.files,
      }
    })
    .sort(compareByTitle)
}

function getSourcePageFile(block) {
  return block.files.find((file) => {
    if (typeof file.path !== "string" || file.type !== "registry:page") {
      return false
    }

    return file.path.includes("/source/app/") && /\/page\.tsx?$/.test(file.path)
  })
}

async function validateReferencedFiles(blocks) {
  for (const block of blocks) {
    for (const file of block.files) {
      if (typeof file.path !== "string" || !(await fileExists(path.join(root, file.path)))) {
        throw new Error(`Registry item "${block.name}" references a missing file: ${file.path}`)
      }
    }
  }
}

async function collectPreviewEntries(blocks) {
  const grouped = new Map()

  for (const block of blocks) {
    const sourcePageFile = getSourcePageFile(block)

    if (!sourcePageFile || !(await fileExists(path.join(root, sourcePageFile.path)))) {
      continue
    }

    const group = grouped.get(block.category) ?? {
      category: block.category,
      entries: [],
    }

    group.entries.push({
      slug: block.name,
      importName: `${toPascalCase(block.name)}Preview`,
      importPath: `@/${sourcePageFile.path.replace(/\.tsx?$/, "")}`,
    })
    grouped.set(block.category, group)
  }

  return Array.from(grouped.values())
    .sort((a, b) => compareByTitle({ title: toTitle(a.category) }, { title: toTitle(b.category) }))
    .map((group) => ({
      ...group,
      entries: group.entries.sort((a, b) => a.slug.localeCompare(b.slug, "en", { sensitivity: "base" })),
    }))
}

function collectCategoryPreviewEntries(blocks) {
  const categorySlugs = Array.from(new Set(blocks.map((block) => block.category)))

  return categorySlugs
    .sort((a, b) => toTitle(a).localeCompare(toTitle(b), "en", { sensitivity: "base" }))
    .map((slug) => ({
      slug,
      title: toTitle(slug),
      componentName: `${toPascalCase(slug)}CategoryPreview`,
    }))
}

async function collectAvailableCategoryPreviewComponents() {
  const source = await readFile(categoryPreviewComponentsPath, "utf8")
  const matches = source.matchAll(/export function (\w+CategoryPreview)\s*\(/g)

  return new Set(
    Array.from(matches, (match) => match[1]).filter(
      (name) => name !== "GenericCategoryPreview",
    ),
  )
}

function renderPreviewMap(groups) {
  const lines = [
    "// THIS FILE IS AUTO-GENERATED by `pnpm generate`. DO NOT EDIT MANUALLY.",
    'import type React from "react"',
    "",
  ]

  for (const group of groups) {
    lines.push(`// ${toTitle(group.category)} Blocks`)
    for (const entry of group.entries) {
      lines.push(`import ${entry.importName} from "${entry.importPath}"`)
    }
    lines.push("")
  }

  lines.push("export const previewMap: Record<string, React.ComponentType> = {")
  for (const group of groups) {
    lines.push(`  // ${toTitle(group.category)}`)
    for (const entry of group.entries) {
      lines.push(`  "${entry.slug}": ${entry.importName},`)
    }
  }
  lines.push("}")
  lines.push("")

  return lines.join("\n")
}

function renderCategoryPreviewMap(categories, availableComponentNames) {
  const specificComponentNames = Array.from(
    new Set(
      categories
        .map((category) => category.componentName)
        .filter((componentName) => availableComponentNames.has(componentName)),
    ),
  ).sort((a, b) => a.localeCompare(b, "en", { sensitivity: "base" }))

  const importedComponentNames = [
    ...specificComponentNames,
    "GenericCategoryPreview",
  ].sort((a, b) => a.localeCompare(b, "en", { sensitivity: "base" }))

  const lines = [
    "// THIS FILE IS AUTO-GENERATED by `pnpm generate`. DO NOT EDIT MANUALLY.",
    'import type { ComponentType } from "react"',
    "import {",
  ]

  for (const componentName of importedComponentNames) {
    lines.push(`  ${componentName},`)
  }

  lines.push(
    "  type BlockCategoryPreviewProps,",
    '} from "@/components/block-category-previews"',
    "",
    "export const blockCategoryPreviewMap: Record<string, ComponentType<BlockCategoryPreviewProps>> = {",
  )

  for (const category of categories) {
    const componentName = availableComponentNames.has(category.componentName)
      ? category.componentName
      : "GenericCategoryPreview"

    lines.push(`  "${category.slug}": ${componentName},`)
  }

  lines.push(
    "}",
    "",
    "export function getBlockCategoryPreview(categorySlug: string): ComponentType<BlockCategoryPreviewProps> {",
    "  return blockCategoryPreviewMap[categorySlug] ?? GenericCategoryPreview",
    "}",
    "",
  )

  return lines.join("\n")
}

async function main() {
  const registry = await readJson(registryPath)
  const blocks = getBlockItems(registry)

  if (blocks.length === 0) {
    throw new Error("No block items were found in root registry.json.")
  }

  await validateReferencedFiles(blocks)

  const previewGroups = await collectPreviewEntries(blocks)
  const previewCount = previewGroups.reduce((sum, group) => sum + group.entries.length, 0)

  if (previewCount === 0) {
    throw new Error("No previewable blocks were found in root registry.json.")
  }

  await writeFile(previewMapPath, renderPreviewMap(previewGroups), "utf8")
  console.log(
    `Wrote ${previewCount} previews to ${path.relative(root, previewMapPath)}`,
  )

  const [categoryPreviewEntries, availableCategoryPreviewComponents] = await Promise.all([
    collectCategoryPreviewEntries(blocks),
    collectAvailableCategoryPreviewComponents(),
  ])

  await writeFile(
    categoryPreviewMapPath,
    renderCategoryPreviewMap(categoryPreviewEntries, availableCategoryPreviewComponents),
    "utf8",
  )
  console.log(
    `Wrote ${categoryPreviewEntries.length} category previews to ${path.relative(root, categoryPreviewMapPath)}`,
  )

  console.log(
    `Successfully generated preview maps from ${blocks.length} root registry blocks.`,
  )
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error)
  process.exitCode = 1
})
